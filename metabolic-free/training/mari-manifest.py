VARIANTS = ("Breathing", "Tempo", "Common Mistake")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


jobs = []
for clip, (name, *cues) in E.items():
    src = SRC / f"{clip}.MOV"
    if not src.exists():
        raise SystemExit(f"missing source: {src}")
    for variant, cue in zip(VARIANTS, cues):
        jobs.append({
            "src": str(src),
            "out": f"{slug(name)}__{slug(variant)}__{clip.replace(' ', '')}.mp4",
            "name": name,
            "variant": variant,
            "cue": cue,
        })

out = Path(__file__).parent / "manifest.json"
out.write_text(json.dumps(jobs, indent=1))
print(f"{len(E)} clips -> {len(jobs)} jobs")
assert len({j['out'] for j in jobs}) == len(jobs), "duplicate output filenames"
print("all output names unique")
