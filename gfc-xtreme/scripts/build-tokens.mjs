// brand.config.json -> the generated artefacts. Nothing downstream is hand-edited:
//   overlay/frontend/src/gfc-brand.css   the accent preset, app chrome and login screen
//   overlay/frontend/manifest.partial.json   PWA name and theme colour
// Run: node gfc-xtreme/scripts/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const brand = JSON.parse(readFileSync(join(root, 'brand/brand.config.json'), 'utf8'))
const { identity: I, color: C, imagery: M, logoPlacement: L } = brand

// Safari before 16.2 has no color-mix(), and upstream's own test
// (frontend/src/color-mix-fallback.test.js) fails any rule that uses it without a plain
// declaration of the same property first. A gym's members are on iPhones, so this is a real
// device concern and not box-ticking: every color-mix() below is preceded by its rgba().
const rgba = (hex, a) => {
  const n = parseInt(hex.slice(1), 16)
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`
}

const banner = `/* GENERATED by gfc-xtreme/scripts/build-tokens.mjs from brand/brand.config.json.
   Do not edit this file — edit the config and run \`node gfc-xtreme/scripts/build-tokens.mjs\`.
   ${I.name} */`

const css = `${banner}

/* ---------------------------------------------------------------- accent --
   openGym picks the accent from a named preset (frontend/src/lib/format.js ACCENTS
   and the :root[data-accent=...] rules in index.css). "gfc" is registered as one more
   preset rather than forced in as a custom colour, so Settings, the swatch picker, the
   Android theme colour and the contrast-aware --on-acc all keep working untouched. */
:root[data-accent="gfc"] {
  --acc:    ${C.accent.hex};
  --acc-2:  ${C.accentPress.hex};
  --on-acc: ${C.onAccent.hex};   /* measured ${C.onAccent.contrastOnAccent} against the accent; white is only 3.04 */
}

/* The dark surfaces carry a trace of the gym photography's cool shadow instead of a
   flat neutral grey, which is what keeps the orange reading as lit rather than printed. */
:root[data-brand="gfc"] {
  --bg:        ${C.ink.hex};
  --surface:   ${C.surface.hex};
  --surface-2: ${C.surface2.hex};
  --label:     ${C.label.hex};
  --gfc-line:  ${C.line.hex};
}

/* ------------------------------------------------------------------ mark --
   The logo sits in the upper-left of the app chrome, above the content and out of the
   scroll, clear of the status bar and of the connection banner when one is showing
   (--sat and --conn are openGym's own). */
.gfc-mark {
  position: fixed;
  top: calc(var(--sat, 0px) + var(--conn, 0px) + ${L.appHeader.insetY}px);
  left: ${L.appHeader.insetX}px;
  height: ${L.appHeader.height}px;
  width: auto;
  z-index: 40;
  pointer-events: none;
  user-select: none;
  -webkit-user-drag: none;
}
.gfc-mark--login {
  top: calc(var(--sat, 0px) + ${L.login.insetY}px);
  left: ${L.login.insetX}px;
  height: ${L.login.height}px;
}
/* Reduced to the wordmark alone on very narrow screens, so it never crowds a title. */
@media (max-width: 360px) { .gfc-mark { height: ${Math.round(L.appHeader.height * 0.82)}px } }

/* ----------------------------------------------------------------- login --
   The gym photograph, with a scrim that is nearly opaque where the form sits and light
   at the top where the mark sits. Without the scrim the white labels fall onto the
   bright rack lighting and lose contrast exactly where it matters.
   The 480px file is served to small screens; the photo is decorative, so it is a
   background rather than an <img> and is announced to nobody. */
.gfc-login-bg {
  position: fixed;
  inset: 0;
  z-index: -1;
  background-image:
    linear-gradient(180deg, ${M.scrimTop} 0%, rgba(0,0,0,.70) 52%, ${M.scrimBottom} 100%),
    url("/brand/gym-bg.jpg");
  background-size: cover;
  background-position: center 38%;
  background-repeat: no-repeat;
}
@media (max-width: 520px) {
  .gfc-login-bg {
    background-image:
      linear-gradient(180deg, ${M.scrimTop} 0%, rgba(0,0,0,.70) 52%, ${M.scrimBottom} 100%),
      url("/brand/gym-bg-480.jpg");
  }
}
/* A photograph behind a form is a motion and legibility risk for anyone who has asked
   for less of both; those users get the flat brand background. */
@media (prefers-reduced-motion: reduce), (prefers-contrast: more) {
  .gfc-login-bg { background-image: none; background-color: ${C.ink.hex} }
}

/* The sign-in card floats on the photo rather than sitting in a panel: a translucent
   fill with a blur keeps the gym visible without putting anything behind the labels. */
.gfc-login-card {
  background: ${rgba(C.surface.hex, 0.82)};
  background: color-mix(in srgb, ${C.surface.hex} 82%, transparent);
  backdrop-filter: blur(18px) saturate(1.1);
  -webkit-backdrop-filter: blur(18px) saturate(1.1);
  border-color: ${rgba(C.line.hex, 0.7)};
  border-color: color-mix(in srgb, ${C.line.hex} 70%, transparent);
  border-style: solid;
  border-width: var(--hair, .5px);
  border-radius: var(--r-xl, 22px);
}
@supports not (backdrop-filter: blur(1px)) {
  .gfc-login-card {
    background: ${rgba(C.surface.hex, 0.94)};
    background: color-mix(in srgb, ${C.surface.hex} 94%, transparent);
  }
}
`

const manifest = {
  name: I.name,
  short_name: I.short,
  description: I.tagline,
  theme_color: C.ink.hex,
  background_color: C.ink.hex
}

mkdirSync(join(root, 'overlay/frontend/src'), { recursive: true })
writeFileSync(join(root, 'overlay/frontend/src/gfc-brand.css'), css)
writeFileSync(join(root, 'overlay/frontend/manifest.partial.json'), JSON.stringify(manifest, null, 2) + '\n')

console.log(`${I.name} — tokens built`)
console.log(`  accent ${C.accent.hex} / press ${C.accentPress.hex} / ink-on-accent ${C.onAccent.hex}`)
console.log('  overlay/frontend/src/gfc-brand.css')
console.log('  overlay/frontend/manifest.partial.json')
